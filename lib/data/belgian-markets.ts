function hash(s: string): number {
  return [...s].reduce((a, c) => a + c.charCodeAt(0), 0);
}

function photo(type: MarketType, slug: string): string {
  const pool = PHOTOS[type];
  return pool[hash(slug) % pool.length];
}

function lastOrder(end: string): string {
  const [h, m] = end.split(':').map(Number);
  const t = Math.max(0, h * 60 + m - 60);
  return `${String(Math.floor(t / 60)).padStart(2, '0')}:${String(t % 60).padStart(2, '0')}`;
}

/** [jours, début, fin] — jours = un nombre ou un tableau */
function h(
  days: number | number[],
  start: string,
  end: string,
): Array<{ dayOfWeek: number; startTime: string; endTime: string; lastOrderTime: string }> {
  return (Array.isArray(days) ? days : [days]).map((dayOfWeek) => ({
    dayOfWeek,
    startTime: start,
    endTime: end,
    lastOrderTime: lastOrder(end),
  }));
}

type Draft = Omit<BelgianMarketSeed, 'imageUrl' | 'zoneRadiusKm' | 'highlights'> & {
  imageUrl?: string;
  zoneRadiusKm?: number;
  highlights?: string[];
};

function M(d: Draft): BelgianMarketSeed {
  return {
    ...d,
    zoneRadiusKm: d.zoneRadiusKm ?? 6,
    imageUrl: d.imageUrl ?? photo(d.type, d.slug),
    highlights: d.highlights ?? [],
  };
}

